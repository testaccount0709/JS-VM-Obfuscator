import { traverse } from "../utils/babel.js";
import type { NodePath, Scope } from "@babel/traverse";
import * as t from "@babel/types";
import type { Context } from "../core/context.js";
import { isRuntimePath } from "../core/context.js";
import type { ScopeInfo } from "./scope-analysis.js";
import { analyzeRenameBlocking } from "./scope-analysis.js";
import { confusingName, minifiedName, DECOY_GLOBAL_NAMES, isReserved } from "../utils/names.js";
import { mbaExpr } from "../utils/mba.js";

/** Collect all identifier names referenced as globals (no binding) anywhere. */
function collectGlobalRefs(ast: t.File): Set<string> {
  const globals = new Set<string>();
  traverse(ast, {
    ReferencedIdentifier(path: NodePath<t.Identifier>) {
      if (!path.scope.getBinding(path.node.name)) globals.add(path.node.name);
    },
  });
  return globals;
}

function bindingTouchesModuleSyntax(binding: { referencePaths: NodePath[]; path: NodePath }): boolean {
  if (binding.path.isImportSpecifier?.() || binding.path.isImportDefaultSpecifier?.() || binding.path.isImportNamespaceSpecifier?.()) {
    return true;
  }
  for (const ref of binding.referencePaths) {
    let cur: NodePath | null = ref.parentPath;
    if (cur && (cur.isExportSpecifier() || cur.isExportDefaultDeclaration() || cur.isExportNamedDeclaration())) return true;
  }
  return false;
}

export function renameIdentifiers(ast: t.File, ctx: Context, info: ScopeInfo): void {
  const level = ctx.options.identifiers;
  if (level <= 0) {
    // still record declared names so later passes avoid collisions
    traverse(ast, {
      Scope(path: NodePath) {
        for (const name of Object.keys(path.scope.bindings)) ctx.usedNames.add(name);
      },
    });
    return;
  }

  // Recompute eval/with rename-blocking from the CURRENT AST: structural passes
  // (CFF, VM, scatter, reshape, rfactory) replace/relocate declaration nodes, so
  // blocking sets captured during scope-analysis are stale. Analyzable eval
  // sources block only the bindings they reference; everything else in those
  // scopes is free to rename.
  const rblock = analyzeRenameBlocking(ast);
  if (rblock.scopes.size > 0 || rblock.bindings.size > 0) {
    info.renameBlockedScopes = rblock.scopes;
    info.renameBlockedBindings = rblock.bindings;
  }

  const globalRefs = collectGlobalRefs(ast);
  // Runtime public names (IIFE export property names) must NOT be renamed: they
  // are referenced from program-scope member expressions like `rt.pubMethod(...)`
  // but defined as object-property keys inside the IIFE. Renaming the reference
  // without renaming the key breaks the runtime.
  const rtPublic = [...ctx.runtime.publicNames()];
  for (const name of rtPublic) globalRefs.delete(name);
  const scopes = new Set<Scope>();
  traverse(ast, {
    Scope(path: NodePath) {
      scopes.add(path.scope);
    },
  });

  // `taken` must include every name already in use anywhere in the tree
  // (globals + all names declared/generated by earlier passes). Otherwise a
  // nested binding can be renamed to a name that shadows an outer binding
  // (e.g. a spill function) still referenced from inside the nested scope —
  // the reference then resolves to the wrong binding at runtime.
  const taken = new Set<string>([...globalRefs, ...ctx.usedNames]);
  let counter = 0;

  const renameOne = (scope: Scope, name: string): void => {
    const binding = scope.bindings[name];
    if (!binding) return;
    if (info.renameBlockedScopes.has(binding.scope.path.node)) return;
    if (info.renameBlockedBindings.has(binding.path.node)) return;
    if (binding.kind === "module") return;
    if (bindingTouchesModuleSyntax(binding)) return;
    if (name === "arguments" || name === "undefined") return;
    if (isReserved(name)) return;

    let next: string;
    if (level >= 2) {
      next = confusingName(ctx.rng, taken, 2);
    } else {
      do {
        next = minifiedName(counter++, taken);
      } while (globalRefs.has(next) || isReserved(next));
    }
    try {
      scope.rename(name, next);
      ctx.usedNames.add(next);
    } catch {
      // rename can fail on pathological scopes; skip silently
    }
  };

  // Rename innermost-first to reduce interference between nested scopes.
  const scopeList = [...scopes];
  scopeList.sort((a, b) => depthOf(b.path) - depthOf(a.path));
  for (const scope of scopeList) {
    scope.crawl();
    for (const name of Object.keys(scope.bindings)) {
      renameOne(scope, name);
    }
  }

  if (level >= 2) injectShadowDecoys(ast, ctx, globalRefs);

  if (level >= 2) manglePrivateNames(ast, ctx);

  // refresh used names for later passes
  traverse(ast, {
    Scope(path: NodePath) {
      for (const name of Object.keys(path.scope.bindings)) ctx.usedNames.add(name);
    },
  });
}

/**
 * Private-name mangling: rename each class's `#field` / `#method` / `#accessor`
 * names to per-build confusing identifiers. Private names are lexically scoped
 * to their class and are not bindings, so the renaming pass leaves them intact
 * — yet they leak the original source's structure (`#base`, `#inner`, ...).
 */
function manglePrivateNames(ast: t.File, ctx: Context): void {
  traverse(ast, {
    Class(path: NodePath<t.Class>) {
      const renameMap = new Map<string, string>();
      path.traverse({
        PrivateName(p: NodePath<t.PrivateName>) {
          const id = p.node.id;
          if (!t.isIdentifier(id)) return;
          if (renameMap.has(id.name)) {
            id.name = renameMap.get(id.name)!;
          } else {
            const fresh = confusingName(ctx.rng, ctx.usedNames, 2);
            renameMap.set(id.name, fresh);
            ctx.usedNames.add(fresh);
            id.name = fresh;
          }
        },
      });
    },
  });
}

function depthOf(path: NodePath): number {
  let d = 0;
  let cur: NodePath | null = path;
  while (cur) {
    d++;
    cur = cur.parentPath;
  }
  return d;
}

/**
 * Shadow decoys: declare unrelated locals named after greppable globals
 * (Function, eval, fetch...) in scopes that never reference those names.
 */
function injectShadowDecoys(ast: t.File, ctx: Context, globalRefs: Set<string>): void {
  const candidates: NodePath<t.BlockStatement>[] = [];
  traverse(ast, {
    Function(path: NodePath<t.Function>) {
      if (isRuntimePath(path, ctx)) return;
      if (t.isBlockStatement(path.node.body)) candidates.push(path.get("body") as NodePath<t.BlockStatement>);
    },
  });
  if (candidates.length === 0) return;

  const count = Math.min(candidates.length, ctx.rng.range(2, 6));
  const chosen = ctx.rng.pickIndices(count, candidates.length);
  for (const idx of chosen) {
    const body = candidates[idx];
    // which decoy names are safe here (not referenced anywhere in the subtree, not bound)
    const referenced = new Set<string>();
    body.traverse({
      ReferencedIdentifier(path: NodePath<t.Identifier | t.JSXIdentifier>) {
        referenced.add(path.node.name);
      },
    });
    const pool = DECOY_GLOBAL_NAMES.filter(
      (n) => !referenced.has(n) && !globalRefs.has(n) && !body.scope.getBinding(n) && !ctx.usedNames.has(n),
    );
    if (pool.length === 0) continue;
    const name = ctx.rng.pick(pool);
    ctx.usedNames.add(name);
    const junk = t.variableDeclaration("var", [
      t.variableDeclarator(t.identifier(name), mbaExpr(ctx.rng, ctx.rng.range(1, 0x7fff), 2)),
    ]);
    body.node.body.unshift(junk);
    body.scope.crawl();
  }
}
